foreach ($m in $mobs) {
  if ($Only -and -not ($Only -contains $m.name)) { continue }
  if (-not $keyed[$m.sheet]) { $p = [Px]::Load("$src\ai$($m.sheet).png"); [Paper]::Key($p, 60); $keyed[$m.sheet] = $p }
