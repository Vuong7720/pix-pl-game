function LegsX($p, $x, $y, $w, $h) {
  $sum = 0; $n = 0
  for ($yy = $y + $h - 40; $yy -lt $y + $h - 6; $yy++) {
    for ($xx = $x; $xx -lt $x + $w; $xx++) { if ($p.D[(($yy * $p.W) + $xx) * 4 + 3] -gt 0) { $sum += $xx; $n++ } }
  }
  if ($n -eq 0) { return $x + $w / 2 }
  return $sum / $n
}

