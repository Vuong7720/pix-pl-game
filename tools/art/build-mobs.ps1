  $sheet = [Px]::Blank($CW * 6, $CH * 4)
  $r = 0
  foreach ($row in $m.rows) {
    $f = 0
    foreach ($fr in $row) {
      $x, $y, $w, $h = $fr
      $lx = LegsX $p $x $y $w $h
      $sheet.Paste($p.Crop($x, $y, $w, $h), $f * $CW + $AX - [int]($lx - $x), $r * $CH + $FOOT - $h)
      $f++
    }
    $r++
  }
  $small = $sheet.Resize([int]($sheet.W * $K), [int]($sheet.H * $K))
